package backend;

public class seaLife {
	 public String name;
	    public String species;
	    public String habitat;
	    public String diet;
	    public String conservStatus;

	    public seaLife(String name, String species, String habitat,
	                   String diet, String conservStatus) {
	        this.name = name;
	        this.species = species;
	        this.habitat = habitat;
	        this.diet = diet;
	        this.conservStatus = conservStatus;
	    }
}
